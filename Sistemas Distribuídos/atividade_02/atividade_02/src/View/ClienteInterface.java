    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed
        // TODO add your handling code here:
        String nome = txtNome.getText().trim();
        String data = txtData.getText().trim();
        //validação para inserir algo no nome
        if(nome.isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe o nome completo");
            txtNome.requestFocus();
            return;
        }
        // O nome deve possuir pelo menos duas palavras 
        String[] partesNome = nome.split("\\s+"); 
        if (partesNome.length < 2) {
            JOptionPane.showMessageDialog( this, "Informe o nome completo, contendo pelo menos nome e sobrenome." );
            txtNome.requestFocus();
            return; 
        }
        //validação para inserir algo na data
        if(data.isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe a data de nascimento");
            txtData.requestFocus();
            return;
        }
        /*o tipo da data na classe pessoa é LocalDate*/
        DateTimeFormatter formatador = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        LocalDate dataNascimento;
        
        try{
            dataNascimento = LocalDate.parse(data,formatador);
        }catch(DateTimeParseException e){
            JOptionPane.showMessageDialog(this, "Data inválida. Informe a data no formato dd/mm/aaaa");
            txtData.requestFocus();
            return;
        }
        
        //Instancia a Pessoa
        Pessoa pessoa = new Pessoa(nome,dataNascimento);
        
        try{
             Pessoa resposta = controller.enviarPessoa(pessoa);
        
            txtNomeCompleto.setText(resposta.getNomeCompleto());
            txtDataNas.setText(resposta.getDtNascimento().format(formatador));
            txtEmail.setText(resposta.getEmail());
        }catch(IOException | ClassNotFoundException e){
            JOptionPane.showMessageDialog(this, "Erro ao comunicar com o servidor: " +e.getMessage() );
        }
        
    }//GEN-LAST:event_btnEnviarActionPerformed

