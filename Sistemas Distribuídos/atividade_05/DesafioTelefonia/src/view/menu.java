    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String celularBusca = txtCelular.getText().trim();

        if (celularBusca.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite um número de celular.");
            return;
        }
        if (servico == null) {
            JOptionPane.showMessageDialog(this, "Não há conexão com o servidor.");
            return;
        }
        try {
            /*Solicita ao servidor os dados da sessão do número informado*/
            String dadosSessao = servico.verificaSessao(celularBusca);

            if (dadosSessao != null) {
                txaDados.setText(dadosSessao);
            } else {
                txaDados.setText("");
                JOptionPane.showMessageDialog(this, "Sessão não encontrada!");
            }

        } catch (RemoteException e) {
            /*Atualiza o status caso ocorra um erro na comunicação*/
            lblStatus.setText("Não foi possível se conectar ao servidor.");
            lblStatus.setForeground(java.awt.Color.RED);
            servico = null;
            JOptionPane.showMessageDialog(this, "Erro na comunicação com o servidor.");
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

